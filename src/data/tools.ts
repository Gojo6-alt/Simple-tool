export const POPULAR_TOOLS = TOOLS.filter((t) => t.isFeatured || t.popularity >= 94).slice(0, 8);

export function getToolBySlug(slug: string): ToolConfig | undefined {
  return TOOLS.find((t) => t.slug === slug);
}

export function getToolsByCategory(category: string): ToolConfig[] {
  return TOOLS.filter((t) => t.category === category);
}

export function searchTools(query: string): ToolConfig[] {
  const clean = query.trim().toLowerCase();
  if (!clean) return TOOLS;
  return TOOLS.filter((t) => {
    return (
      t.name.toLowerCase().includes(clean) ||
      t.description.toLowerCase().includes(clean) ||
      t.category.toLowerCase().includes(clean) ||
      t.keywords.some((k) => k.toLowerCase().includes(clean))
    );
  });
}
